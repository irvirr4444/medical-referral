export function countScenarioBuckets(scenarios: WorkflowScenario[]) {
  const counts = {
    ready: 0,
    attention: 0,
    blocked: 0,
    approval: 0,
    openCases: 0,
    totalCases: 0,
    scenarioCount: 0,
  }
  for (const scenario of scenarios) {
    counts.scenarioCount += 1
    counts[scenario.bucket] += 1
    for (const item of scenario.cases) {
      counts.totalCases += 1
      if (scenarioCaseIsOpen(item.status)) counts.openCases += 1
    }
  }
  return counts
}

export function assertScenarioCoverage(scenarios: WorkflowScenario[] = createInitialWorkflowScenarios()) {
  const byTab: Record<string, WorkflowScenario[]> = {}
  for (const scenario of scenarios) {
    byTab[scenario.tab] ??= []
    byTab[scenario.tab].push(scenario)
    if (scenario.cases.length < 2 || scenario.cases.length > 4) {
      throw new Error(`${scenario.id} must have 2–4 examples (got ${scenario.cases.length})`)
    }
  }
  return byTab
}
