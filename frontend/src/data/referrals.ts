function mondayPreview(
  name: string,
  source: string,
  diagnosis: string,
  blockers: string[] = [],
) {
  return {
    itemName: name,
    board: 'Master Sheet',
    group: 'In intake',
    columns: [
      { label: 'Patient', value: name },
      { label: 'Referring facility', value: source },
      { label: 'Diagnosis', value: diagnosis },
      { label: 'Sent By', value: 'info@westcoastwound.example' },
      { label: 'Stage', value: 'In intake' },
    ],
    updateComment:
      'Automation-prepared intake details retained for review: insurance, requested services, and clinical summary.',
    agencyRelation: source,
    blockers,
  }
}

